import { z } from 'zod';
import { SAVE_VERSION } from '@/engine/constants';

const renovationCategorySchema = z.enum(['kitchen', 'bathroom', 'flooring', 'smart-home', 'layout', 'commercial-fitout', 'maintenance-overhaul']);
const rentStrategySchema = z.enum(['conservative', 'market', 'aggressive']);
const rentalModeSchema = z.enum(['room-rental', 'whole-unit', 'corporate-lease', 'student-shared', 'commercial-lease']);
const tenantProfileSchema = z.enum(['local-family', 'expat-pmet', 'student-tenants', 'sme-commercial']);
const mortgageFinancingModeSchema = z.enum(['bank', 'hdb-concessionary']);
const runRouteSchema = z.enum([
  'bto-upgrader',
  'single-resale',
  'pr-private-climber',
  'foreign-investor',
  'heartland-landlord',
  'commercial-operator',
  'fire-homeowner',
]);
const buyerProfileSchema = z.object({
  residencyStatus: z.enum(['sc', 'spr', 'foreigner']),
  householdProfile: z.enum(['couple-family', 'single-35-plus', 'single-under-35', 'foreigner-investor']),
  age: z.number(),
});

const renovationProjectSchema = z.object({
  id: z.string(),
  templateId: z.string(),
  propertyId: z.string(),
  category: renovationCategorySchema,
  label: z.string(),
  cost: z.number(),
  durationMonths: z.number(),
  remainingMonths: z.number(),
  rentUpliftPct: z.number(),
  resaleUpliftPct: z.number(),
  satisfactionUplift: z.number(),
  riskPct: z.number(),
  conditionDelta: z.number(),
  status: z.enum(['planned', 'active', 'completed', 'overrun', 'cancelled']),
  startedTurn: z.number(),
});

const tenantStateSchema = z.object({
  profileId: tenantProfileSchema,
  rentalMode: rentalModeSchema,
  leaseStartTurn: z.number(),
  leaseEndTurn: z.number(),
  satisfaction: z.number(),
  rentStrategy: rentStrategySchema,
  askingRent: z.number(),
  contractedRent: z.number(),
  defaultRiskPct: z.number(),
  renewalIntent: z.number(),
  lastLeaseDecisionTurn: z.number().optional(),
});

const maintenanceIssueSchema = z.object({
  id: z.string(),
  propertyId: z.string(),
  category: z.enum(['plumbing', 'electrical', 'aircon', 'waterproofing', 'appliance', 'common-area', 'tenant-damage']),
  severity: z.enum(['minor', 'major', 'urgent']),
  label: z.string().optional(),
  riskTag: z.string().optional(),
  estimatedCost: z.number(),
  satisfactionImpact: z.number(),
  valueImpactPct: z.number(),
  recurrenceRiskPct: z.number(),
  status: z.enum(['open', 'repaired', 'deferred', 'insured']),
});

const ownedPropertySchema = z.object({
  propertyId: z.string(),
  purchasePrice: z.number(),
  purchaseDate: z.string(),
  currentValue: z.number(),
  isRented: z.boolean(),
  monthlyRental: z.number(),
  renovationLevel: z.number(),
  loanId: z.string().optional(),
  occupancyStatus: z.enum(['owner-occupied', 'vacant', 'tenanted', 'renovating', 'listed']).optional(),
  tenantQuality: z.number().optional(),
  vacancyMonths: z.number().optional(),
  maintenanceCost: z.number().optional(),
  propertyTax: z.number().optional(),
  listingChannel: z.string().optional(),
  conditionScore: z.number().optional(),
  mopRemainingMonths: z.number().optional(),
  activeRenovation: renovationProjectSchema.optional(),
  completedRenovations: z.array(renovationCategorySchema).optional(),
  tenant: tenantStateSchema.optional(),
  openMaintenanceIssues: z.array(maintenanceIssueSchema).optional(),
  rentStrategy: rentStrategySchema.optional(),
  floorPlanId: z.string().optional(),
  financingMode: mortgageFinancingModeSchema.optional(),
  hdbResaleLevyPaid: z.number().optional(),
});

const loanSchema = z.object({
  id: z.string(),
  type: z.enum(['mortgage', 'renovation', 'personal']),
  principal: z.number(),
  remainingBalance: z.number(),
  interestRate: z.number(),
  monthlyPayment: z.number(),
  termYears: z.number(),
  startDate: z.string(),
  propertyId: z.string().optional(),
  isPaid: z.boolean(),
  financingMode: mortgageFinancingModeSchema.optional(),
});

const playerSchema = z.object({
  name: z.string(),
  age: z.number(),
  careerId: z.string().optional(),
  career: z.string().optional(),
  salary: z.number(),
  cash: z.number(),
  cpfOrdinary: z.number(),
  cpfSpecial: z.number(),
  cpfMedisave: z.number(),
  creditScore: z.number(),
  properties: z.array(ownedPropertySchema),
  loans: z.array(loanSchema),
  maritalStatus: z.enum(['single', 'married', 'divorced']),
  children: z.number(),
  year: z.number(),
  month: z.number(),
  turnCount: z.number(),
  totalNetWorth: z.number(),
  achievements: z.array(z.string()),
  difficulty: z.enum(['easy', 'normal', 'hard', 'tycoon']),
  totalRentalIncome: z.number(),
  totalPropertySalesProfit: z.number(),
  bankruptcyStrikes: z.number().optional(),
  life: z.object({
    energy: z.number(),
    stress: z.number(),
    reputation: z.number(),
    careerMomentum: z.number(),
    householdLoad: z.number(),
    householdSupport: z.number(),
    livingArrangement: z.enum(['with-parents', 'renting-room', 'renting-flat']),
    selectedPrimaryActionId: z.string().nullable(),
    selectedSecondaryActionId: z.string().nullable(),
    trainingTrackId: z.string().nullable(),
    trainingMonthsRemaining: z.number(),
    schemeProgress: z.object({
      skillsFuture: z.number(),
      firstTimerGrant: z.number(),
      householdSupport: z.number(),
    }),
    lastMonthSummary: z.object({
      primaryActionId: z.string(),
      secondaryActionId: z.string().nullable(),
      cashDelta: z.number(),
      energyDelta: z.number(),
      stressDelta: z.number(),
      reputationDelta: z.number(),
      careerMomentumDelta: z.number(),
      householdSupportDelta: z.number(),
      notes: z.array(z.string()),
    }).nullable(),
  }).optional(),
  careerGrowthModifier: z.number().optional(),
  careerRiskModifier: z.number().optional(),
  careerVolatilityModifier: z.number().optional(),
  lastCareerReviewTurn: z.number().optional(),
  nextJobSwitchTurn: z.number().optional(),
  firstHomePurchased: z.boolean().optional(),
  ownedPrivateHome: z.boolean().optional(),
  careerProgressionProfile: z.object({
    reviewCount: z.number(),
    lastOutcome: z.enum(['promotion', 'bonus', 'steady', 'setback']).nullable(),
    lastSalaryDelta: z.number(),
    lastBonus: z.number(),
  }).optional(),
  careerReviewHistory: z.array(z.object({
    turn: z.number(),
    outcome: z.enum(['promotion', 'bonus', 'steady', 'setback']).nullable(),
    salaryDelta: z.number(),
    bonus: z.number(),
  })).optional(),
  buyerProfile: buyerProfileSchema.optional(),
  runRouteId: runRouteSchema.optional(),
  reserve: z.object({
    targetMonths: z.number(),
    allocatedCash: z.number(),
    autoTopUpPct: z.number(),
    lastCoveredCost: z.number().optional(),
  }).optional(),
  operationHistory: z.array(z.object({
    id: z.string(),
    turn: z.number(),
    propertyId: z.string().optional(),
    title: z.string(),
    detail: z.string(),
    tone: z.enum(['good', 'warn', 'bad', 'neutral']),
  })).optional(),
});

export const saveSchema = z.object({
  version: z.literal(SAVE_VERSION),
  player: playerSchema,
  market: z.object({
    interestRate: z.number(),
    priceIndex: z.number(),
    rentalIndex: z.number(),
    volatility: z.number(),
    lastEvent: z.string().nullable(),
    monthlyPriceChangePct: z.number().optional(),
    monthlyRentalChangePct: z.number().optional(),
    monthlyInterestRateChangePct: z.number().optional(),
    lastHeadline: z.string().nullable().optional(),
    lastSummary: z.string().nullable().optional(),
    newsFeed: z.array(z.object({
      id: z.string(),
      turn: z.number(),
      month: z.number(),
      year: z.number(),
      headline: z.string(),
      detail: z.string(),
      category: z.enum(['Rates', 'Demand', 'Supply', 'Policy', 'Macro', 'Infrastructure']),
      tone: z.enum(['bullish', 'bearish', 'neutral']),
      priceChangePct: z.number(),
      rentalChangePct: z.number(),
      rateChangePct: z.number(),
    })).optional(),
  }),
  settings: z.object({
    soundEnabled: z.boolean(),
    musicEnabled: z.boolean(),
    animationSpeed: z.enum(['slow', 'normal', 'fast']),
    autoSave: z.boolean(),
    difficulty: z.enum(['easy', 'normal', 'hard', 'tycoon']),
    compactMode: z.boolean().optional(),
  }),
  isGameActive: z.boolean(),
  currentScenario: z.string().nullable(),
  rngSeed: z.number(),
  rngState: z.number(),
});

export type ValidatedSave = z.infer<typeof saveSchema>;
